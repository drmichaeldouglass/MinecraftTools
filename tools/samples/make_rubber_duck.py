#!/usr/bin/env python3
"""Generate the sample rubber duck model (``rubber_duck.obj``).

The duck is built from low-poly ellipsoids (body, tail, head, beak and two
eyes) and saved as a Wavefront OBJ with per-vertex colours
(``v x y z r g b``), the same layout many photogrammetry tools export. It is
Y-up and faces +Z, so it ends up facing south in Minecraft.

Regenerate the model and the statue with::

    python3 tools/samples/make_rubber_duck.py
    python3 tools/model_to_structure.py model tools/samples/rubber_duck.obj \\
        --size 16 --name rubber_duck --title "Rubber Duck"
"""

import math
import os

YELLOW = (1.0, 0.84, 0.10)
ORANGE = (1.0, 0.50, 0.05)
BLACK = (0.04, 0.04, 0.05)

# (centre, radii, tilt about the x axis in degrees, colour)
PARTS = [
    ((0.0, 0.55, -0.05), (0.72, 0.50, 0.95), 0, YELLOW),      # body
    ((0.0, 0.88, -0.92), (0.30, 0.22, 0.34), -35, YELLOW),    # tail, pointing up and back
    ((0.62, 0.66, -0.10), (0.16, 0.28, 0.50), 0, YELLOW),     # right wing
    ((-0.62, 0.66, -0.10), (0.16, 0.28, 0.50), 0, YELLOW),    # left wing
    ((0.0, 1.30, 0.50), (0.46, 0.46, 0.46), 0, YELLOW),       # head
    ((0.0, 1.18, 0.98), (0.28, 0.10, 0.27), 0, ORANGE),       # beak
    ((0.25, 1.45, 0.86), (0.11, 0.11, 0.11), 0, BLACK),       # right eye
    ((-0.25, 1.45, 0.86), (0.11, 0.11, 0.11), 0, BLACK),      # left eye
]


def ellipsoid(centre, radii, tilt, segments=14, rings=8):
    """Return (vertices, faces) of a UV ellipsoid; faces are quads and pole triangles."""
    cx, cy, cz = centre
    c, s = math.cos(math.radians(tilt)), math.sin(math.radians(tilt))
    vertices = []
    for ring in range(rings + 1):
        phi = math.pi * ring / rings                      # 0 at the top pole
        for seg in range(segments if 0 < ring < rings else 1):
            theta = 2 * math.pi * seg / segments
            x = radii[0] * math.sin(phi) * math.cos(theta)
            y = radii[1] * math.cos(phi)
            z = radii[2] * math.sin(phi) * math.sin(theta)
            # Tilt about the x axis, then move into place.
            vertices.append((cx + x, cy + y * c - z * s, cz + y * s + z * c))

    def index(ring, seg):
        if ring == 0:
            return 0
        if ring == rings:
            return 1 + (rings - 1) * segments
        return 1 + (ring - 1) * segments + seg % segments

    faces = []
    for seg in range(segments):
        faces.append((index(0, 0), index(1, seg + 1), index(1, seg)))
        faces.append((index(rings, 0), index(rings - 1, seg), index(rings - 1, seg + 1)))
        for ring in range(1, rings - 1):
            faces.append((index(ring, seg), index(ring, seg + 1),
                          index(ring + 1, seg + 1), index(ring + 1, seg)))
    return vertices, faces


def main():
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rubber_duck.obj")
    lines = ["# Rubber duck sample for tools/model_to_structure.py",
             "# Generated by tools/samples/make_rubber_duck.py: Y up, facing +Z,",
             "# vertex colours written as 'v x y z r g b'."]
    offset = 1
    for centre, radii, tilt, colour in PARTS:
        vertices, faces = ellipsoid(centre, radii, tilt)
        lines.append("o part")
        lines += [f"v {x:.4f} {y:.4f} {z:.4f} {colour[0]:.3f} {colour[1]:.3f} {colour[2]:.3f}"
                  for x, y, z in vertices]
        lines += ["f " + " ".join(str(offset + i) for i in face) for face in faces]
        offset += len(vertices)
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"Wrote {os.path.relpath(out_path)}")


if __name__ == "__main__":
    main()
